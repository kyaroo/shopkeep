import 'package:flutter/material.dart';
import 'package:easy_localization/easy_localization.dart';
import 'package:provider/provider.dart';
import '../build_config.dart';
import '../data/config.dart';
import '../providers/catalog_provider.dart';
import 'catalog_home_page.dart';

/// Admin setup screen: create / manage shops.
///
/// This is a separate app entry point in the admin APK. It never shows
/// checkout, inventory, or sales — only shop management.
class AdminSetupScreen extends StatefulWidget {
  const AdminSetupScreen({super.key});

  @override
  State<AdminSetupScreen> createState() => _AdminSetupScreenState();
}

class _AdminSetupScreenState extends State<AdminSetupScreen> {
  final _nameController = TextEditingController();
  final _shopKeyController = TextEditingController();
  List<String> _shopKeys = [];
  bool _loading = true;

  @override
  void initState() {
    super.initState();
    _loadShops();
    _shopKeyController.addListener(() {});
    _nameController.addListener(() {
      if (_shopKeyController.text.isEmpty) {
        _shopKeyController.text = _slugify(_nameController.text);
      }
    });
  }

  Future<void> _loadShops() async {
    final list = await Config.getShopList();
    if (mounted) {
      setState(() {
        _shopKeys = list;
        _loading = false;
      });
    }
  }

  Future<void> _addShop() async {
    final name = _nameController.text.trim();
    if (name.isEmpty) return;
    final key = _shopKeyController.text.trim().toLowerCase();
    if (key.isEmpty) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('shopKeyRequired'.tr())),
        );
      }
      return;
    }
    final existing = await Config.getShopList();
    if (existing.contains(key)) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('shopKeyDuplicate'.tr())),
        );
      }
      return;
    }
    await Config.addShop(key, name);
    await Config.setCurrentShopKey(key);
    await Config.saveBusinessName(name);
    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('shopCreated'.tr())),
      );
      Navigator.of(context).pop();
    }
  }

  String _slugify(String input) {
    return input.trim().toLowerCase().replaceAll(RegExp(r'[^a-z0-9]+'), '_').replaceAll(RegExp(r'^_+|_+$'), '');
  }

  void _confirmDelete(String key) {
    showDialog(
      context: context,
      builder: (_) => AlertDialog(
        title: Text('deleteShop'.tr()),
        content: Text('deleteShopConfirm'.tr(namedArgs: {'key': key})),
        actions: [
          TextButton(onPressed: () => Navigator.pop(context), child: Text('cancel'.tr())),
          TextButton(
            onPressed: () {
              Config.removeShop(key);
              if (mounted) Navigator.pop(context);
            },
            child: Text('delete'.tr(), style: TextStyle(color: Theme.of(context).colorScheme.error)),
          ),
        ],
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: Text('adminSetup'.tr())),
      body: _loading
          ? const Center(child: CircularProgressIndicator())
          : ListView(
              padding: const EdgeInsets.all(16),
              children: [
                Card(
                  child: Padding(
                    padding: const EdgeInsets.all(16),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text('addShop'.tr(),
                            style: Theme.of(context).textTheme.titleLarge),
                        const SizedBox(height: 12),
                        TextField(
                          controller: _nameController,
                          decoration: InputDecoration(
                            labelText: 'businessName'.tr(),
                            border: const OutlineInputBorder(),
                          ),
                        ),
                        const SizedBox(height: 8),
                        TextField(
                          controller: _shopKeyController,
                          decoration: InputDecoration(
                            labelText: 'shopKey'.tr(),
                            border: const OutlineInputBorder(),
                            helperText: 'autoGenerated'.tr(),
                          ),
                        ),
                        const SizedBox(height: 12),
                        ElevatedButton(
                          onPressed: _addShop,
                          child: Text('createShop'.tr()),
                        ),
                      ],
                    ),
                  ),
                ),
                const SizedBox(height: 16),
                Card(
                  child: Padding(
                    padding: const EdgeInsets.all(16),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text('shopsList'.tr(),
                            style: Theme.of(context).textTheme.titleLarge),
                        const SizedBox(height: 12),
                        if (_shopKeys.isEmpty)
                          Text('noShopsFound'.tr())
                        else
                          ..._shopKeys.map((key) {
                            return ListTile(
                              title: Text(key),
                              subtitle: Text('shopKey'.tr() + ': ' + key),
                              trailing: PopupMenuButton<String>(
                                onSelected: (v) {
                                  if (v == 'delete') _confirmDelete(key);
                                },
                                itemBuilder: (_) => [
                                  PopupMenuItem<String>(
                                    value: 'delete',
                                    child: Text('delete'.tr(),
                                        style: TextStyle(
                                            color: Colors.red)),
                                  ),
                                ],
                              ),
                            );
                          }),
                      ],
                    ),
                  ),
                ),
                if (kIsAdmin) ...[
                  const SizedBox(height: 16),
                  Card(
                    child: Padding(
                      padding: const EdgeInsets.all(16),
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Text('Catalog (founder)',
                              style: Theme.of(context).textTheme.titleLarge),
                          const SizedBox(height: 12),
                          ElevatedButton.icon(
                            onPressed: () {
                              Navigator.of(context).push(
                                MaterialPageRoute(
                                  builder: (_) => ChangeNotifierProvider(
                                    create: (_) => CatalogProvider()..init(),
                                    child: const CatalogHomePage(),
                                  ),
                                ),
                              );
                            },
                            icon: const Icon(Icons.qr_code_scanner),
                            label: const Text('Open Catalog'),
                          ),
                        ],
                      ),
                    ),
                  ),
                ],
              ],
            ),
    );
  }
}
